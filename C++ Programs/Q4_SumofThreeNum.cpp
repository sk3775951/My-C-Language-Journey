// C++ Program to print: Sum of Three Numbers - 

#include <iostream>
using namespace std ;
int main () {
    int x, y, z ;
    cout << "Enter the 1st Number: " ;
    cin >> x ;
    cout << "Enter the 2nd Number: " ;
    cin >> y ;
    cout << "Enter the 3rd Number: " ;
    cin >> z ;
    cout << "Sum of these numbers is: " << x+y+z << endl ;
}